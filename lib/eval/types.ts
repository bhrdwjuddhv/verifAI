// ──────────────────────────────────────────────────────────────
// lib/eval/types.ts — Data model types for the evaluation harness
// ──────────────────────────────────────────────────────────────

import type { VerdictCategory } from '@/lib/verdict';

/** Ground-truth label assigned to each sample before evaluation begins. */
export type GroundTruthLabel = 'authentic' | 'manipulated' | 'inconclusive';

/** Human reviewer's judgment of VerifAI's prediction for a single sample. */
export type HumanJudgment = 'correct' | 'incorrect' | 'partially_correct';

/**
 * A single evaluation sample — one piece of media with a known ground-truth label.
 * The 300-sample dataset is deterministically generated by sampleGenerator.ts.
 */
export interface EvalSample {
  /** Unique sample identifier, e.g. "EVAL-001" */
  id: string;
  /** Reference filename / media path (synthetic for demo) */
  mediaRef: string;
  /** The correct label (known truth) */
  groundTruthLabel: GroundTruthLabel;
  /** Optional: the "correct" trust score (0-100). Not always available. */
  groundTruthScore?: number;
  /** VerifAI's predicted trust score (0-100) using current fusion weights */
  predictedScore: number;
  /** VerifAI's predicted verdict category derived from predictedScore */
  predictedVerdict: VerdictCategory;
  /** Per-module breakdown scores (0-100 each) */
  moduleScores: ModuleScores;
  /** Which split this sample belongs to */
  split: 'working' | 'heldout';
}

/** Per-module scores feeding into the fusion engine. */
export interface ModuleScores {
  faceForgery: number;
  frequencyGan: number;
  audioSpoof: number;
  exifEla: number;
  c2pa: number;
}

/** The 5 fusion weights — one scalar per detection module. */
export interface FusionWeights {
  faceForgery: number;
  frequencyGan: number;
  audioSpoof: number;
  exifEla: number;
  c2pa: number;
}

/** All module weight keys, useful for iteration. */
export const FUSION_WEIGHT_KEYS: (keyof FusionWeights)[] = [
  'faceForgery',
  'frequencyGan',
  'audioSpoof',
  'exifEla',
  'c2pa',
];

/** Default equal weights. */
export const DEFAULT_FUSION_WEIGHTS: FusionWeights = {
  faceForgery: 0.2,
  frequencyGan: 0.2,
  audioSpoof: 0.2,
  exifEla: 0.2,
  c2pa: 0.2,
};

/** A persisted human judgment for a single eval sample. */
export interface JudgedResult {
  sampleId: string;
  predictedScore: number;
  predictedVerdict: VerdictCategory;
  moduleScores: ModuleScores;
  humanJudgment: HumanJudgment;
  reviewerNote?: string;
  timestamp: string;
}

/** Result of a single tuning pass. */
export interface TuningPassResult {
  id: string;
  timestamp: string;
  beforeWeights: FusionWeights;
  afterWeights: FusionWeights;
  workingSetAccuracyBefore: number;
  workingSetAccuracyAfter: number;
  heldOutAccuracyBefore: number;
  heldOutAccuracyAfter: number;
  applied: boolean;
}

/** Accuracy metrics computed from judged results. */
export interface EvalMetrics {
  totalJudged: number;
  accuracy: number;
  /** Per-verdict-class precision and recall */
  perClass: {
    genuine: { precision: number; recall: number; count: number };
    suspicious: { precision: number; recall: number; count: number };
    manipulated: { precision: number; recall: number; count: number };
  };
  /** Mean absolute calibration error (predicted score vs actual outcome) */
  calibrationError: number;
}
